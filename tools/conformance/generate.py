#!/usr/bin/env python3
"""Generates the Kotlin conformance tests from djot.js's test files (see conformance/README.md).

Parses each file exactly as djot.js's src/functional.spec.ts does, and writes one test class per
file with one @Test per case into djot/src/commonTest/.../conformance/.
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SRC = os.path.join(ROOT, "conformance", "djot.js")
OUT = os.path.join(ROOT, "djot", "src", "commonTest", "kotlin", "com", "vitorpamplona", "djot", "conformance")
HEADER = os.path.join(ROOT, "spotless", "copyright.kt")

# The list and order of djot.js's functional.spec.ts. filters.test is not in it.
TEST_FILES = [
    "attributes.test",
    "block_quote.test",
    "code_blocks.test",
    "definition_lists.test",
    "symb.test",
    "emphasis.test",
    "escapes.test",
    "fenced_divs.test",
    "footnotes.test",
    "headings.test",
    "insert_delete_mark.test",
    "links_and_images.test",
    "lists.test",
    "math.test",
    "para.test",
    "raw.test",
    "regression.test",
    "smart.test",
    "spans.test",
    "sourcepos.test",
    "super_subscript.test",
    "tables.test",
    "task_lists.test",
    "thematic_breaks.test",
    "verbatim.test",
]


def parse_tests(path):
    # JS: readFileSync(...).split('\n'); a trailing newline leaves a final empty line.
    with open(path, encoding="utf-8", newline="") as f:
        lines = f.read().split("\n")
    idx = 0

    def get_line():
        nonlocal idx
        if idx < len(lines):
            line = lines[idx]
            idx += 1
            return line
        return None

    tests = []
    while True:
        inp = ""
        out = ""
        line = get_line()
        while line is not None and not re.match(r"^```", line):
            line = get_line()
        testlinenum = idx
        if line is None:
            break
        m = re.match(r"^(`+)\s*(.*)", line)
        if not m:
            raise ValueError("Test start line did not have expected form: " + line)
        ticks = re.compile("^" + m.group(1))
        options = m.group(2)
        line = get_line()
        while line is not None and not re.match(r"^[.!]$", line):
            inp += line + "\n"
            line = get_line()
        line = get_line()
        while line is not None and not ticks.match(line):
            out += line + "\n"
            line = get_line()
        tests.append((testlinenum, options, inp, out))
    return tests


def kotlin_string(s):
    """A Kotlin string literal for s: ASCII only, every other UTF-16 unit as a \\u escape."""
    out = ['"']
    data = s.encode("utf-16-le", "surrogatepass")
    for i in range(0, len(data), 2):
        code = data[i] | (data[i + 1] << 8)
        c = chr(code) if code < 0xD800 or code > 0xDFFF else None
        if c == "\\":
            out.append("\\\\")
        elif c == '"':
            out.append('\\"')
        elif c == "$":
            out.append("\\$")
        elif c == "\n":
            out.append("\\n")
        elif c == "\r":
            out.append("\\r")
        elif c == "\t":
            out.append("\\t")
        elif c is not None and 0x20 <= code < 0x7F:
            out.append(c)
        else:
            out.append("\\u%04X" % code)
    out.append('"')
    return "".join(out)


def class_name(file):
    base = file[: -len(".test")]
    return "".join(part.capitalize() for part in base.split("_")) + "ConformanceTest"


def main():
    with open(HEADER, encoding="utf-8") as f:
        header = f.read().rstrip("\n") + "\n"
    os.makedirs(OUT, exist_ok=True)
    for old in os.listdir(OUT):
        if old.endswith("ConformanceTest.kt"):
            os.remove(os.path.join(OUT, old))
    total = 0
    for file in TEST_FILES:
        tests = parse_tests(os.path.join(SRC, file))
        name = class_name(file)
        body = [
            header,
            "package com.vitorpamplona.djot.conformance\n",
            "\n",
            "import kotlin.test.Test\n",
            "\n",
            "// Generated by tools/conformance/generate.py from conformance/djot.js/%s. Do not edit.\n" % file,
            "class %s {\n" % name,
        ]
        for i, (linenum, options, inp, out) in enumerate(tests):
            if i > 0:
                body.append("\n")
            body.append("    @Test\n")
            body.append("    fun line%d() =\n" % linenum)
            body.append("        assertConformance(\n")
            body.append("            file = %s,\n" % kotlin_string(file))
            body.append("            line = %d,\n" % linenum)
            body.append("            options = %s,\n" % kotlin_string(options))
            body.append("            input = %s,\n" % kotlin_string(inp))
            body.append("            expected = %s,\n" % kotlin_string(out))
            body.append("        )\n")
        body.append("}\n")
        with open(os.path.join(OUT, name + ".kt"), "w", encoding="utf-8", newline="\n") as f:
            f.write("".join(body))
        total += len(tests)
        print("%s: %d cases" % (file, len(tests)))
    print("total: %d cases" % total)


if __name__ == "__main__":
    sys.exit(main())
